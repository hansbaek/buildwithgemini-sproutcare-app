def main():
    print(f"Connecting to Firestore for project: {PROJECT_ID}...")
    db = firestore.Client(project=PROJECT_ID)
    plants_ref = db.collection("plants")

    print(f"Starting seed of {len(PLANTS_DATA)} plant varieties into Firestore...")
    batch = db.batch()
    count = 0

    for plant in PLANTS_DATA:
        doc_id = plant["id"]
        doc_ref = plants_ref.document(doc_id)
        batch.set(doc_ref, plant, merge=True)
        count += 1

        if count % 400 == 0:
            batch.commit()
            print(f"Committed {count} plants...")
            batch = db.batch()

    batch.commit()
    print(f"Successfully seeded/updated {count} plant varieties in Firestore 'plants' collection!")

if __name__ == "__main__":
    main()
